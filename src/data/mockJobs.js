const HOUR_MS = 60 * 60 * 1000

// Posted dates are relative to when the app loads, so the sample listings keep a realistic
// spread of ages ("3 hours ago" … "6 weeks ago") however long after they were written.
function hoursAgo(hours) {
  return new Date(Date.now() - hours * HOUR_MS).toISOString()
}

function daysAgo(days) {
  return hoursAgo(days * 24)
}

function yearly(min, max) {
  return { min, max, currency: 'USD', period: 'year' }
}

function hourly(min, max) {
  return { min, max, currency: 'USD', period: 'hour' }
}

